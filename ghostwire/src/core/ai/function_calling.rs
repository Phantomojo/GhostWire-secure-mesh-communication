// FunctionGemma Integration for GhostWire
// On-device tool calling via FunctionGemma (270M params)
//
// FunctionGemma generates structured JSON function calls from natural language,
// then explains results back in natural language — "unified action and chat".
//
// Architecture:
//   1. User sends natural language command
//   2. FunctionGemma parses it into a structured function call (JSON schema)
//   3. GhostWire executes the corresponding action
//   4. Results are fed back to FunctionGemma for natural language response
//
// Model: functiongemma:270m (32K context, 85% tool-calling accuracy)
// Backend: LiteRT-LM, Ollama, or MLX

use reqwest::Client;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::sync::Arc;
use std::time::Duration;
use tokio::sync::RwLock;

// ============================================================
// Tool Schema Definitions
// ============================================================

/// JSON schema for a single function/tool parameter
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionParameter {
    #[serde(rename = "type")]
    pub param_type: String,
    pub description: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub enum_values: Option<Vec<String>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub items: Option<Box<FunctionParameter>>,
}

/// JSON schema for a function/tool
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionSchema {
    pub name: String,
    pub description: String,
    pub parameters: HashMap<String, FunctionParameter>,
    pub required: Vec<String>,
}

/// A function call generated by FunctionGemma
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionCall {
    pub name: String,
    pub arguments: serde_json::Value,
}

/// Complete FunctionGemma response
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionGemmaResponse {
    /// The function call to execute (may be empty if no tool match)
    #[serde(default)]
    pub function_call: Option<FunctionCall>,
    /// Natural language explanation (always present)
    pub explanation: String,
    /// Confidence in the function call (0.0-1.0)
    #[serde(default = "default_confidence")]
    pub confidence: f32,
}

fn default_confidence() -> f32 {
    0.0
}

/// Result of executing a function call
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionResult {
    pub function_name: String,
    pub success: bool,
    pub output: serde_json::Value,
    pub error: Option<String>,
}

