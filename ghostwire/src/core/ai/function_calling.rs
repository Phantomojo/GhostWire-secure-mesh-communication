impl DeviceClass {
    /// Recommended Gemma 4 model for this device class
    pub fn recommended_gemma4_model(&self) -> &'static str {
        match self {
            DeviceClass::Phone => "gemma4:e2b",
            DeviceClass::Tablet => "gemma4:e4b",
            DeviceClass::RaspberryPi => "gemma4:e2b",
            DeviceClass::Laptop => "gemma4:26b",
            DeviceClass::Server => "gemma4:31b",
        }
    }

    /// Estimated available RAM in MB
    pub fn estimated_ram_mb(&self) -> u64 {
        match self {
            DeviceClass::Phone => 6144,
            DeviceClass::Tablet => 8192,
            DeviceClass::RaspberryPi => 4096,
            DeviceClass::Laptop => 16384,
            DeviceClass::Server => 65536,
        }
    }
}

/// Detect the current device class based on system info
pub fn detect_device_class() -> DeviceClass {
    let mem_info = read_meminfo();
    let has_gpu = detect_gpu();
    let is_arm = is_arm_architecture();

    // Check for Raspberry Pi first (ARM + specific mem range)
    if is_arm && mem_info < 8192 {
        if is_raspberry_pi() {
            return DeviceClass::RaspberryPi;
        }
        return DeviceClass::Phone;
    }

    if mem_info < 6000 {
        return DeviceClass::Phone;
    } else if mem_info < 12000 {
        return DeviceClass::Tablet;
    } else if mem_info < 32000 {
        return DeviceClass::Laptop;
    } else if has_gpu || mem_info >= 65536 {
        return DeviceClass::Server;
    }

    DeviceClass::Laptop
}

/// Read total RAM from /proc/meminfo (Linux)
fn read_meminfo() -> u64 {
    if let Ok(content) = std::fs::read_to_string("/proc/meminfo") {
        for line in content.lines() {
            if line.starts_with("MemTotal:") {
                let parts: Vec<&str> = line.split_whitespace().collect();
                if parts.len() >= 2 {
                    if let Ok(kb) = parts[1].parse::<u64>() {
                        return kb / 1024; // Convert KB to MB
                    }
                }
            }
        }
    }
    8192 // Default: assume laptop-class
}

/// Detect if a GPU is available
fn detect_gpu() -> bool {
    std::path::Path::new("/dev/dri").exists()
        || std::path::Path::new("/dev/nvidia0").exists()
        || std::env::var("CUDA_VISIBLE_DEVICES").is_ok()
        || std::env::var("ROCR_VISIBLE_DEVICES").is_ok()
}

/// Check if running on ARM architecture
fn is_arm_architecture() -> bool {
    let arch = std::env::consts::ARCH;
    arch == "aarch64" || arch == "arm" || arch == "armv7"
}

/// Check if running on a Raspberry Pi
fn is_raspberry_pi() -> bool {
    if let Ok(content) = std::fs::read_to_string("/proc/cpuinfo") {
        return content.to_lowercase().contains("raspberry");
    }
    if let Ok(content) = std::fs::read_to_string("/proc/device-tree/model") {
        return content.to_lowercase().contains("raspberry");
    }
    false
}

